// Persistent Store Helper
export class BarberFlowStore {
  private static STORAGE_KEY = 'barberflow_crm_state_v1';

  static loadState() {
    try {
      const data = localStorage.getItem(this.STORAGE_KEY);
      if (data) {
        return JSON.parse(data);
      }
    } catch (e) {
      console.warn('Failed to parse state from localStorage', e);
    }
    return {
      tenants: INITIAL_TENANTS,
      services: INITIAL_SERVICES,
      barbers: INITIAL_BARBERS,
      customers: INITIAL_CUSTOMERS,
      appointments: INITIAL_APPOINTMENTS,
      leads: INITIAL_LEADS,
      products: INITIAL_PRODUCTS,
      transactions: INITIAL_TRANSACTIONS,
      campaigns: INITIAL_CAMPAIGNS,
      whatsappLogs: INITIAL_WHATSAPP_LOGS,
      waitingQueue: INITIAL_WAITING_QUEUE,
      activeTenantId: 'barbearia-exclusiva' as TenantId,
    };
  }

  static saveState(state: any) {
    try {
      localStorage.setItem(this.STORAGE_KEY, JSON.stringify(state));
    } catch (e) {
      console.error('Failed to save state to localStorage', e);
    }
  }
}
